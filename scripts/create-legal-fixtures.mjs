import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = "tests/fixtures/legal";
mkdirSync(root, { recursive: true });

const files = {
  "small-file/readme.txt": "Legal local fixture for LumaTorrent tests.\n",
  "multi-file/a.txt": "A\n",
  "multi-file/b.txt": "B\n",
  "unicode/नमस्ते.txt": "Unicode filename fixture.\n",
  "many-small-files/001.txt": "1\n",
  "many-small-files/002.txt": "2\n",
};

for (const [rel, content] of Object.entries(files)) {
  const full = join(root, rel);
  mkdirSync(full.split("/").slice(0, -1).join("/"), { recursive: true });
  writeFileSync(full, content);
}

writeFileSync(
  join(root, "manifest.json"),
  JSON.stringify(
    {
      purpose:
        "Legal local fixture files for tests. Torrent files are not generated by this placeholder script.",
      generatedAt: new Date().toISOString(),
      files: Object.keys(files),
    },
    null,
    2,
  ),
);

console.log(`Legal fixture placeholders created in ${root}`);
